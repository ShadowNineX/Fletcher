using System.Globalization;
using System.Text;
using Antlr4.Runtime;
using Antlr4.Runtime.Misc;
using Fletcher.Compiler.Syntax;
using Fletcher.Compiler.Translation.Generated;
using static Fletcher.Compiler.Translation.Generated.PortableCParser;

namespace Fletcher.Compiler.Translation;

public static class CTranspiler
{
    public static (string? Source, Diagnostic? Error) Translate(string path, string source)
    {
        // Bail on the first error. A recovered parse could silently change C semantics.
        var lexer = new PortableCLexer(new AntlrInputStream(source));
        var parser = new PortableCParser(new CommonTokenStream(lexer)) { ErrorHandler = new BailErrorStrategy() };
        lexer.RemoveErrorListeners();
        lexer.AddErrorListener(new LexError());
        parser.RemoveErrorListeners();
        parser.AddErrorListener(new ParseError());
        try
        {
            return (new Translator().Generate(parser.translationUnit()), null);
        }
        catch (ParseCanceledException)
        {
            var token = parser.CurrentToken;
            return (null, DiagnosticAt(token.Line, token.Column, $"Unsupported C syntax near '{token.Text}'."));
        }
        catch (TranslationException error)
        {
            return (null, DiagnosticAt(error.Line, error.Column, error.Message));
        }

        Diagnostic DiagnosticAt(int line, int column, string message)
        {
            var start = 0;
            for (var row = 1; row < line; row++)
                start = source.IndexOf('\n', start) + 1;
            return new Diagnostic(path, new TextSpan(start + column, 1), message);
        }
    }

    private enum Scalar { Void, Int, Unsigned, Bit }
    private sealed record Value(string Code, Scalar Type);
    private sealed record Local(Scalar Type, int? Length, bool ReadOnly);

    private sealed class Function(string name, Scalar result, Scalar[] parameters, bool isStatic)
    {
        public string Name { get; } = name;
        public string FletcherName => (IsStatic ? "c_fn_" : "C_") + Name;
        public Scalar Result { get; } = result;
        public Scalar[] Parameters { get; } = parameters;
        public bool IsStatic { get; } = isStatic;
        public FunctionDeclarationContext? Definition { get; set; }
        public HashSet<Function> Calls { get; } = [];
    }

    private sealed class Translator
    {
        private readonly Dictionary<string, Function> functions = [with(StringComparer.Ordinal)];
        private readonly Stack<Dictionary<string, Local>> scopes = [];
        private readonly HashSet<Local> loopBounds = [with(ReferenceEqualityComparer.Instance)];
        private readonly StringBuilder output = new();
        private Function current = null!;
        private int indent;
        private bool needsBooleanConversion;

        public string Generate(TranslationUnitContext unit)
        {
            foreach (var declaration in unit.functionDeclaration())
                RegisterFunction(declaration);

            Function[] definitions = [.. functions.Values.Where(function => function.Definition is not null)];
            if (definitions.Length == 0)
                throw Error(unit.Start, "Expected at least one C function definition.");

            Line("// Generated by fletcher transpile-c.");
            Line("package cport");
            foreach (var function in definitions)
                EmitFunction(function);
            CheckCalls(definitions);

            if (needsBooleanConversion)
            {
                Line("");
                Line("func c_boolean(value bit) int {");
                Line("    if value { return 1 }");
                Line("    return 0");
                Line("}");
            }
            return output.ToString();
        }

        private void RegisterFunction(FunctionDeclarationContext declaration)
        {
            var name = declaration.Identifier().Symbol;
            var result = declaration.integerType() is { } type ? Type(type) : Scalar.Void;
            Scalar[] parameters = [.. declaration.parameter().Select(parameter => Type(parameter.integerType()))];
            var isStatic = declaration.STATIC() is not null;
            if (!functions.TryGetValue(name.Text, out var function))
            {
                function = new Function(name.Text, result, parameters, isStatic);
                functions.Add(name.Text, function);
            }
            if (function.Result != result || !parameters.SequenceEqual(function.Parameters) || function.IsStatic != isStatic)
                throw Error(name, $"Conflicting declarations of '{name.Text}'.");
            if (declaration.block() is null)
                return;
            if (function.Definition is not null)
                throw Error(name, $"Duplicate definition of '{name.Text}'.");
            function.Definition = declaration;
        }

        private void EmitFunction(Function function)
        {
            current = function;
            var definition = function.Definition!;
            PushScope();
            var parameters = definition.parameter().Select(parameter =>
            {
                var name = parameter.Identifier()?.Symbol ?? throw Error(parameter.Start, "A definition requires named parameters.");
                var type = Type(parameter.integerType());
                Declare(name, new Local(type, null, parameter.CONST() is not null));
                return $"{Variable(name.Text)} {FletcherType(type)}";
            });
            var result = function.Result == Scalar.Void ? "" : " " + FletcherType(function.Result);
            Line("");
            Line($"func {function.FletcherName}({string.Join(", ", parameters)}){result} {{");
            indent++;
            var returns = EmitBlockContents(definition.block());
            if (!returns && function.Result != Scalar.Void)
                throw Error(definition.Identifier().Symbol, $"'{function.Name}' needs an explicit return on every path.");
            indent--;
            Line("}");
            scopes.Pop();
        }

        private bool EmitBlockContents(BlockContext block)
        {
            var returns = false;
            foreach (var statement in block.statement())
                returns |= Emit(statement);
            return returns;
        }

        private bool EmitBody(StatementContext body)
        {
            PushScope();
            indent++;
            var returns = body is NestedBlockContext nested ? EmitBlockContents(nested.block()) : Emit(body);
            indent--;
            scopes.Pop();
            return returns;
        }

        private bool Emit(StatementContext statement)
        {
            switch (statement)
            {
                case NestedBlockContext nested:
                    Line("{");
                    var returns = EmitBody(nested);
                    Line("}");
                    return returns;
                case LocalDeclarationContext declaration:
                    foreach (var local in declaration.local())
                        EmitLocal(local, Type(declaration.integerType()), declaration.CONST() is not null);
                    break;
                case ConditionalContext conditional:
                    Line($"if {Truth(Expression(conditional.expression()), conditional.Start)} {{");
                    var thenReturns = EmitBody(conditional.statement(0));
                    var elseReturns = false;
                    if (conditional.statement(1) is { } alternate)
                    {
                        Line("} else {");
                        elseReturns = EmitBody(alternate);
                    }
                    Line("}");
                    return thenReturns && elseReturns;
                case CountedLoopContext loop:
                    EmitLoop(loop);
                    break;
                case UpdateStatementContext update:
                    EmitUpdate(update.update());
                    break;
                case ReturnStatementContext ret:
                    var value = ret.expression();
                    if ((value is null) != (current.Result == Scalar.Void))
                        throw Error(ret.Start, "Return value does not match the function's declared type.");
                    Line(value is null ? "return" : $"return {ConvertTo(Expression(value), current.Result, value.Start)}");
                    return true;
                case CallStatementContext call:
                    var called = Call(call.call());
                    Line(called.Type == Scalar.Void ? called.Code : $"_ = {called.Code}");
                    break;
            }
            return false;
        }

        private void EmitLocal(LocalContext context, Scalar type, bool readOnly)
        {
            var name = context.Identifier().Symbol;
            var length = context.Integer() is { } size ? ParseInteger(size.Symbol) : (uint?)null;
            if (length is { } count && (count == 0 || count > Array.MaxLength))
                throw Error(context.Start, $"An array length must be between 1 and {Array.MaxLength}.");

            var fletcherType = length is null ? FletcherType(type) : $"[{length}]{FletcherType(type)}";
            string? initializer = null;
            if (context.initializer() is { } list)
            {
                var items = list.expression();
                if (length is null || items.Length > length)
                    throw Error(list.Start, "The array initializer must fit the declared array length.");
                initializer = fletcherType + "{" + string.Join(", ", items.Select(item => ConvertTo(Expression(item), type, item.Start))) + "}";
            }
            if (context.expression() is { } expression)
            {
                if (length is not null)
                    throw Error(expression.Start, "An array initializer needs braces.");
                initializer = ConvertTo(Expression(expression), type, expression.Start);
            }
            Declare(name, new Local(type, (int?)length, readOnly));
            Line($"var {Variable(name.Text)} {fletcherType}" + (initializer is null ? "" : " = " + initializer));
        }

        private void EmitLoop(CountedLoopContext loop)
        {
            var index = loop.index;
            var step = loop.increment();
            if (ParseInteger(loop.start) != 0 || loop.cursor.Text != index.Text ||
                step.Identifier().GetText() != index.Text || step.op.Text != "++" || loop.bound.Text == index.Text)
                throw Error(loop.Start, "Expected a loop of the form 'for (int i = 0; i < limit; i++)'.");

            Local? bound = null;
            string limit;
            if (loop.bound.Type == PortableCLexer.Identifier)
            {
                bound = FindLocal(loop.bound);
                if (bound.Type != Scalar.Int || bound.Length is not null)
                    throw Error(loop.bound, "The loop limit must be a signed int scalar.");
                limit = Variable(loop.bound.Text);
            }
            else
            {
                var value = ParseInteger(loop.bound);
                if (value > int.MaxValue)
                    throw Error(loop.bound, "The loop limit must fit a signed int.");
                limit = Format(value);
            }

            var protect = bound is not null && loopBounds.Add(bound);
            Line($"for {Variable(index.Text)} := range {limit} {{");
            PushScope();
            Declare(index, new Local(Scalar.Int, null, ReadOnly: true));
            indent++;
            Emit(loop.statement());
            indent--;
            scopes.Pop();
            Line("}");
            if (protect)
                loopBounds.Remove(bound!);
        }

        private void EmitUpdate(UpdateContext update)
        {
            if (update.increment() is { } increment)
            {
                var name = increment.Identifier().Symbol;
                var local = Writable(name);
                if (local.Length is not null)
                    throw Error(name, "Increment and decrement require scalars.");
                var variable = Variable(name.Text);
                var result = Binary(new Value(variable, local.Type), increment.op.Text[..1], new Value("1", Scalar.Int), increment.op);
                Line($"{variable} = {result.Code}");
                return;
            }

            var target = update.lvalue();
            Writable(target.Identifier().Symbol);
            var destination = Access(target);
            var value = Expression(update.expression());
            if (update.op.Text != "=")
                value = Binary(destination, update.op.Text[..^1], value, update.op);
            Line($"{destination.Code} = {ConvertTo(value, destination.Type, update.op)}");
        }

        private Value Expression(ExpressionContext expression) => expression switch
        {
            IntegerContext integer => IntegerValue(integer.Integer().Symbol),
            ReadValueContext read => Access(read.lvalue()),
            InvocationContext invocation => Call(invocation.call()),
            GroupedContext group => Expression(group.expression()),
            CastContext cast => new Value(ConvertTo(Expression(cast.expression()), Type(cast.integerType()), cast.Start), Type(cast.integerType())),
            UnaryContext unary => Unary(unary.op, Expression(unary.expression())),
            BinaryContext binary => Binary(Expression(binary.expression(0)), binary.op.Text, Expression(binary.expression(1)), binary.op),
            _ => throw Error(expression.Start, "Unsupported C expression.")
        };

        private Value Unary(IToken token, Value operand)
        {
            if (token.Text == "!")
                return new Value($"(!{Truth(operand, token)})", Scalar.Bit);
            var type = operand.Type == Scalar.Unsigned ? Scalar.Unsigned : Scalar.Int;
            return new Value($"({token.Text}{ConvertTo(operand, type, token)})", type);
        }

        private Value Binary(Value left, string op, Value right, IToken token)
        {
            if (op is "&&" or "||")
                return new Value($"({Truth(left, token)} {op} {Truth(right, token)})", Scalar.Bit);
            var shift = op is "<<" or ">>";
            var type = left.Type == Scalar.Unsigned || (!shift && right.Type == Scalar.Unsigned) ? Scalar.Unsigned : Scalar.Int;
            var result = op is "==" or "!=" or "<" or "<=" or ">" or ">=" ? Scalar.Bit : type;
            return new Value($"({ConvertTo(left, type, token)} {op} {ConvertTo(right, shift ? Scalar.Int : type, token)})", result);
        }

        private Value Call(CallContext call)
        {
            var name = call.Identifier().Symbol;
            if (scopes.Any(scope => scope.ContainsKey(name.Text)) ||
                !functions.TryGetValue(name.Text, out var target) || target.Definition is null)
                throw Error(name, $"'{name.Text}' must be a direct call to a function defined in this C file.");
            var args = call.expression();
            if (args.Length != target.Parameters.Length)
                throw Error(name, $"'{name.Text}' expects {target.Parameters.Length} arguments.");
            current.Calls.Add(target);
            var values = args.Select((arg, i) => ConvertTo(Expression(arg), target.Parameters[i], arg.Start));
            return new Value($"{target.FletcherName}({string.Join(", ", values)})", target.Result);
        }

        private static void CheckCalls(IEnumerable<Function> functions)
        {
            HashSet<Function> active = [];
            HashSet<Function> visited = [];
            foreach (var function in functions)
                Visit(function);

            void Visit(Function function)
            {
                if (active.Contains(function))
                    throw Error(function.Definition!.Start, $"Recursive call through '{function.Name}' is unsupported.");
                if (!visited.Add(function))
                    return;
                active.Add(function);
                foreach (var call in function.Calls)
                    Visit(call);
                active.Remove(function);
            }
        }

        private Value Access(LvalueContext target)
        {
            var name = target.Identifier().Symbol;
            var local = FindLocal(name);
            var index = target.expression();
            if ((local.Length is null) != (index is null))
                throw Error(name, "Arrays must be accessed by index and scalars cannot be indexed.");
            var suffix = index is null ? "" : $"[{ConvertTo(Expression(index), Scalar.Int, index.Start)}]";
            return new Value(Variable(name.Text) + suffix, local.Type);
        }

        private string ConvertTo(Value value, Scalar type, IToken token)
        {
            if (value.Type == Scalar.Void)
                throw Error(token, "A void call cannot be used as a value.");
            if (value.Type == type)
                return value.Code;
            if (value.Type == Scalar.Bit)
            {
                needsBooleanConversion = true;
                value = new Value($"c_boolean({value.Code})", Scalar.Int);
            }
            return value.Type == type ? value.Code : $"{FletcherType(type)}({value.Code})";
        }

        private static string Truth(Value value, IToken token) => value.Type switch
        {
            Scalar.Void => throw Error(token, "A void call cannot be used as a condition."),
            Scalar.Bit => value.Code,
            _ => $"({value.Code} != 0)"
        };

        private static Value IntegerValue(IToken token)
        {
            var value = ParseInteger(token);
            if (token.Text.EndsWith('u') || token.Text.EndsWith('U') || (token.Text.StartsWith('0') && value > int.MaxValue))
                return new Value($"bits<32>({Format(value)})", Scalar.Unsigned);
            if (value > int.MaxValue)
                throw Error(token, "Decimal literals above INT_MAX need an unsigned suffix or a wider type.");
            return new Value(Format(value), Scalar.Int);
        }

        private static uint ParseInteger(IToken token)
        {
            var text = token.Text.TrimEnd('U', 'u');
            var radix = 10;
            if (text.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
            {
                text = text[2..];
                radix = 16;
            }
            else if (text.StartsWith('0'))
            {
                radix = 8;
            }
            try
            {
                return Convert.ToUInt32(text, radix);
            }
            catch (OverflowException)
            {
                throw Error(token, "Integer literals must fit in 32 bits.");
            }
        }

        private Local Writable(IToken name)
        {
            var local = FindLocal(name);
            if (local.ReadOnly || loopBounds.Contains(local))
                throw Error(name, $"Cannot update '{name.Text}' because it is const, a loop index, or an active loop limit.");
            return local;
        }

        private Local FindLocal(IToken name) => scopes.Select(scope => scope.GetValueOrDefault(name.Text)).OfType<Local>().FirstOrDefault()
            ?? throw Error(name, $"Unknown local '{name.Text}'.");

        private void Declare(IToken name, Local local)
        {
            if (!scopes.Peek().TryAdd(name.Text, local))
                throw Error(name, $"Duplicate local '{name.Text}'.");
        }

        private void PushScope() => scopes.Push([with(StringComparer.Ordinal)]);
        private void Line(string text) => output.Append(' ', indent * 4).AppendLine(text);
        private static Scalar Type(IntegerTypeContext type) => type.UNSIGNED() is null ? Scalar.Int : Scalar.Unsigned;
        private static string FletcherType(Scalar type) => type == Scalar.Unsigned ? "bits<32>" : "int";
        private static string Variable(string name) => "c_var_" + name;
        private static string Format(uint value) => value.ToString(CultureInfo.InvariantCulture);
        private static TranslationException Error(IToken token, string message) => new(token.Line, token.Column, message);
    }

    public sealed class TranslationException(int line, int column, string message) : Exception(message)
    {
        public int Line { get; } = line;
        public int Column { get; } = column;
    }

    private sealed class LexError : IAntlrErrorListener<int>
    {
        public void SyntaxError(TextWriter output, IRecognizer recognizer, int symbol, int line, int charPositionInLine, string msg,
            RecognitionException? e) => throw new TranslationException(line, charPositionInLine, $"Unsupported C token: {msg}");
    }

    private sealed class ParseError : BaseErrorListener
    {
        public override void SyntaxError(TextWriter output, IRecognizer recognizer, IToken offendingSymbol, int line, int charPositionInLine, string msg,
            RecognitionException? e) => throw new TranslationException(line, charPositionInLine, $"Unsupported C syntax: {msg}");
    }
}
